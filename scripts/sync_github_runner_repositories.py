#!/usr/bin/env python3
"""Generate the runner repository lists for k3s-bootstrap's platform Argo CD and for this repo's Ansible.

Source of truth is repo-infra's config.yml: any repository entry with a
truthy `runner` key gets a self-hosted GitHub Actions runner. In
k3s-bootstrap this script writes platform/apps/arc/scale-sets/kustomization.yaml
(the list), creates an overlay for a new repository and deletes the overlay
of a removed one. It never rewrites an existing overlay, so hand edits stay.

It also writes an Ansible group_vars file here, for the monitoring
role's GitHub runner exporter.
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

import yaml

DEFAULT_CONFIG = Path(__file__).resolve().parents[3] / "github" / "repo-infra" / "config.yml"
# A sibling repo checkout, not a subdirectory of this one.
DEFAULT_SCALE_SETS_DIR = (
    Path(__file__).resolve().parents[3] / "bootstrap" / "k3s-bootstrap" / "platform" / "apps" / "arc" / "scale-sets"
)
DEFAULT_ANSIBLE_OUTPUT = (
    Path(__file__).resolve().parents[1] / "ansible" / "inventory" / "group_vars" / "all" / "github_runner_repositories.yml"
)
GITHUB_OWNER = "KandlerLi"


def runner_repositories(config: dict) -> list[dict]:
    """Return the sorted list of {id, repository} entries with runner: true."""
    repositories = []
    for name in sorted(config):
        entry = config[name] or {}
        if entry.get("runner"):
            repositories.append({"id": name, "repository": name})
    return repositories


def render_scale_set_list(repositories: list[dict]) -> str:
    return (
        "# Generated by home-infra's sync_github_runner_repositories.py from repo-infra's runner: true; do not edit.\n"
        + yaml.safe_dump(
            {
                "apiVersion": "kustomize.config.k8s.io/v1beta1",
                "kind": "Kustomization",
                "resources": [entry["id"] for entry in repositories],
            },
            sort_keys=False,
        )
    )


def render_overlay(entry: dict) -> str:
    return f"""# Created by home-infra's sync_github_runner_repositories.py; hand edits stay (the script never rewrites an existing overlay).
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - ../base
nameSuffix: -{entry["id"]}
patches:
  - target:
      kind: Application
    patch: |-
      - op: replace
        path: /spec/source/helm/releaseName
        value: {entry["id"]}
      - op: replace
        path: /spec/source/helm/valuesObject/githubConfigUrl
        value: https://github.com/{GITHUB_OWNER}/{entry["repository"]}
"""


def sync_scale_sets(scale_sets_dir: Path, repositories: list[dict]) -> tuple[list[str], list[str]]:
    """Write the list, create missing overlays and delete obsolete ones; return (created, deleted)."""
    wanted = {entry["id"]: entry for entry in repositories}
    created, deleted = [], []
    for name, entry in wanted.items():
        overlay = scale_sets_dir / name
        if not (overlay / "kustomization.yaml").exists():
            overlay.mkdir(exist_ok=True)
            (overlay / "kustomization.yaml").write_text(render_overlay(entry))
            created.append(name)
    for child in sorted(scale_sets_dir.iterdir()):
        if child.is_dir() and child.name != "base" and child.name not in wanted:
            shutil.rmtree(child)
            deleted.append(child.name)
    (scale_sets_dir / "kustomization.yaml").write_text(render_scale_set_list(repositories))
    return created, deleted


def render_group_vars(repositories: list[dict]) -> str:
    names = [entry["repository"] for entry in repositories]
    return (
        "# Generated by scripts/sync_github_runner_repositories.py from repo-infra's config.yml; do not edit.\n"
        + yaml.safe_dump({"monitoring_github_runner_exporter_repositories": names}, sort_keys=False)
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG, help="Path to repo-infra's config.yml")
    parser.add_argument(
        "--scale-sets-dir",
        type=Path,
        default=DEFAULT_SCALE_SETS_DIR,
        help="k3s-bootstrap's platform/apps/arc/scale-sets directory",
    )
    parser.add_argument(
        "--ansible-output",
        type=Path,
        default=DEFAULT_ANSIBLE_OUTPUT,
        help="Path to the generated Ansible group_vars file",
    )
    args = parser.parse_args(argv)

    if not args.config.exists():
        print(f"error: config file not found: {args.config}", file=sys.stderr)
        return 1

    if not (args.scale_sets_dir / "base").is_dir():
        print(
            f"error: {args.scale_sets_dir}/base not found "
            "(check out KandlerLi/k3s-bootstrap as a sibling, or pass --scale-sets-dir)",
            file=sys.stderr,
        )
        return 1

    config = yaml.safe_load(args.config.read_text()) or {}
    repositories = runner_repositories(config)
    created, deleted = sync_scale_sets(args.scale_sets_dir, repositories)
    args.ansible_output.write_text(render_group_vars(repositories))
    print(
        f"{len(repositories)} runner repositories; overlays created: {created or 'none'}, deleted: {deleted or 'none'}; "
        f"wrote {args.ansible_output}"
    )

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
